/**
 * Escapes text for safe placement in HTML element content or a quoted
 * attribute value.
 */
export function toHTMLText(text: string): string {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}
