    '-u',
    'CODEX_TOOL_CALL_ID',
    'HOME=/tmp/atc-test-home-pear/home',
    'XDG_RUNTIME_DIR=/tmp/atc-test-home-pear/runtime',
    'XDG_CONFIG_HOME=/tmp/atc-test-home-pear/home/.config',
    'XDG_DATA_HOME=/tmp/atc-test-home-pear/home/.local/share',
