// The daemon runs from a compiled binary, so it can't read the mod's files from disk; they are embedded in a generated module.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

function main(): void {
  const modDir = join(import.meta.dir, '..', 'mods', 'atc-bridge');

  // The atc command file stays out: the daemon renders it when it writes the mod.
  const embedded = [
    '.claude-plugin/plugin.json',
    'hooks/hooks.json',
    'hooks/register.ts',
    'hooks/bridge-state.ts',
    'hooks/encode-attribute.ts',
    'hooks/parse-tap-line.ts',
    'hooks/run-tap.ts',
    'hooks/schedule-answered-report.ts',
    'hooks/schedule-delivery.ts',
    'hooks/schedule-notice-delivery.ts',
    'hooks/schedule-notice-reminder.ts',
    'hooks/schedule-unanswered-report.ts',
    'hooks/try-update-conversation.ts',
    'hooks/update-turn-completed.ts',
    'hooks/update-turn-started.ts',
    'hooks/wait-for-step-end.ts',
  ];

  const entries = embedded.map(
    (path) => `  '${path}': ${JSON.stringify(readFileSync(join(modDir, path), 'utf8'))},`,
  );

  writeFileSync(
    join(
      import.meta.dir,
      '..',
      'packages',
      'harnesses',
      'claude',
      'src',
      'bridge',
      'atc-bridge-files.ts',
    ),
    [
      '// Generated by `bun run build:atc-bridge` from mods/atc-bridge; edit the mod, then rerun it.',
      '// oxlint-disable no-template-curly-in-string -- the strings are the mod source, template literals included',
      `export const ATC_BRIDGE_FILES: Readonly<Record<${embedded.map((path) => `'${path}'`).join(' | ')}, string>> = {`,
      ...entries,
      '};',
      '',
    ].join('\n'),
  );
}

main();
