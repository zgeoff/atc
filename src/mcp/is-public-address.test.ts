import { expect, test } from 'bun:test';
import { isPublicAddress } from './is-public-address';

test.each([
  ['104.18.32.47'],
  ['8.8.8.8'],
  ['198.17.255.255'],
  ['198.20.0.1'],
  ['192.0.1.1'],
  ['2606:4700::6810:202f'],
  ['::ffff:8.8.8.8'],
  ['64:ff9b::8.8.8.8'],
  ['2002:808:808::'],
])('it treats %p as public', (address) => {
  expect(isPublicAddress(address)).toBeTrue();
});

